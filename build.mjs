// Emit wimn.user.js — the installable userscript — from the three sources in src/.
//
//   node build.mjs      (or: npm run build)
//
// One artifact, one command: src/config.js + src/bridge.js + src/content.js are CONCATENATED,
// never copied, so a fix to the composer positioning or the UA parser lands in the artifact on the
// next build and nowhere else. `npm test` fails if the checked-in artifact is stale, so it cannot
// quietly rot.

import { readFileSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const read = (name) => readFileSync(new URL(name, here), 'utf8')
const pkg = JSON.parse(read('package.json'))

const header = `// ==UserScript==
// @name         Web Instagram Music Note
// @namespace    https://github.com/HongyiHank/WIMN
// @version      ${pkg.version}
// @description  ${pkg.description}
// @author       HongyiHank
// @license      Apache-2.0
// @match        https://www.instagram.com/*
// @match        https://instagram.com/*
// @downloadURL  https://raw.githubusercontent.com/HongyiHank/WIMN/main/wimn.user.js
// @updateURL    https://raw.githubusercontent.com/HongyiHank/WIMN/main/wimn.user.js
// @run-at       document-start
// @noframes
// @grant        GM_xmlhttpRequest
// @grant        GM_cookie
// @grant        GM_getValue
// @grant        GM_setValue
// @connect      i.instagram.com
// @connect      www.instagram.com
// @connect      raw.githubusercontent.com
// @connect      cdn.jsdelivr.net
// ==/UserScript==
//
// Generated by build.mjs from src/content.js + src/config.js + src/bridge.js.
// Do not edit this file; edit those and rebuild. Needs "cookie access" granted to the script in your
// manager, otherwise sessionid stays invisible and music search answers login_required.
`

// config.js is an ES module; the userscript is one big IIFE, so the keywords go. Anything else
// module-shaped would fail loudly here rather than silently at install time.
const config = read('src/config.js')
  .replace(/^export\s+/gm, '')
  .replace(/^import[\s\S]*?from\s+['"][^'"]+['"]\s*$/gm, '')

// The leading ';' is load-bearing. content.js opens with an IIFE, and the statement before it is an
// object-literal ASSIGNMENT — `x = {...}` followed by `(() => {})()` is not two statements, it is
// one call expression on the literal, which throws "is not a function" before anything runs. An
// empty statement is the cheapest way to close the gap, and it belongs HERE because this is the
// place that knows it is concatenating.
const body = [header, config, read('src/bridge.js').replace('__VERSION__', pkg.version), ';' + read('src/content.js')].join('\n')

// One check on the artifact itself: the manager parses this file, so a syntax error is a silent
// install failure on the user's machine and nothing else here would notice. verify/dom-check.cjs
// then loads the built file in a browser with GM stubs and drives the whole flow.
new Function(body)

writeFileSync(new URL('wimn.user.js', here), body)
console.log('wimn.user.js — ' + (body.length / 1024).toFixed(1) + 'kB, version ' + pkg.version)
